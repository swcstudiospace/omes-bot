    assert sorted(STATUSES) == sorted(fixture["goal_statuses"])
    assert sorted(KINDS) == sorted(fixture["harness_kinds"])
    assert sorted(SCOPES) == sorted(fixture["harness_scopes"])
    assert sorted(STOP_REASONS) == sorted(fixture["autonomous_stop_reasons"])
